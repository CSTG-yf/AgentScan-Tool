// ScanJob is the durable status record behind explicit Agent/resource scans.
// The gateway may keep an in-memory fast path, but the database is the source
// of truth exposed to clients polling after a restart or reconnect.
type ScanJob struct {
	// JobID/Kind are the canonical names. ScanID/Type remain in the wire
	// shape for older desktop builds that still deserialize the scan alias.
	JobID           string         `json:"job_id"`
	ScanID          string         `json:"scan_id,omitempty"`
	Kind            string         `json:"kind"`
	Type            string         `json:"type,omitempty"`
	Mode            string         `json:"mode,omitempty"`
	AgentID         string         `json:"agent_id,omitempty"`
	ResourceID      string         `json:"resource_id,omitempty"`
	Trigger         string         `json:"trigger,omitempty"`
	Scope           map[string]any `json:"scope,omitempty"`
	Result          map[string]any `json:"result,omitempty"`
	Phase           string         `json:"phase,omitempty"`
	Current         int            `json:"current,omitempty"`
	Total           int            `json:"total,omitempty"`
	CancelRequested bool           `json:"cancel_requested,omitempty"`
	IdempotencyKey  string         `json:"idempotency_key,omitempty"`
	RuleVersion     string         `json:"rule_version,omitempty"`
	Status          string         `json:"status"`
	Progress        int            `json:"progress"`
	StartedAt       string         `json:"started_at"`
	FinishedAt      string         `json:"finished_at,omitempty"`
	Error           string         `json:"error,omitempty"`
	CreatedAt       string         `json:"created_at"`
	UpdatedAt       string         `json:"updated_at"`
}

func (j *ScanJob) normalizeAliases() {
	if j == nil {
		return
	}
	if strings.TrimSpace(j.JobID) == "" {
		j.JobID = strings.TrimSpace(j.ScanID)
	}
	if strings.TrimSpace(j.ScanID) == "" {
		j.ScanID = strings.TrimSpace(j.JobID)
	}
	if strings.TrimSpace(j.Kind) == "" {
		j.Kind = strings.TrimSpace(j.Type)
	}
	if strings.TrimSpace(j.Type) == "" {
		j.Type = strings.TrimSpace(j.Kind)
	}
	if j.Current < 0 {
		j.Current = 0
	}
	if j.Total < 0 {
		j.Total = 0
	}
}

func encodeJobJSON(value map[string]any) any {
	if len(value) == 0 {
		return nil
	}
	b, err := json.Marshal(value)
	if err != nil {
		return nil
	}
	return string(b)
}

func decodeJobJSON(raw sql.NullString) map[string]any {
	if !raw.Valid || strings.TrimSpace(raw.String) == "" {
		return nil
	}
	var value map[string]any
	if err := json.Unmarshal([]byte(raw.String), &value); err != nil {
		return nil
	}
	return value
}

// CreateScanJob inserts a queued/running job. Job IDs are generated by the
// gateway so clients can safely retry status reads without creating duplicates.
func (s *Store) CreateScanJob(job ScanJob) error {
	if s == nil || s.db == nil {
		return nil
	}
	job.normalizeAliases()
	job.JobID = strings.TrimSpace(job.JobID)
	if job.JobID == "" {
		return fmt.Errorf("audit: scan job id is required")
	}
	if job.Kind == "" {
		job.Kind = "unknown"
	}
	if job.Status == "" {
		job.Status = "queued"
	}
	if strings.TrimSpace(job.Trigger) == "" {
		job.Trigger = "manual"
	}
	now := time.Now().UTC().Format(time.RFC3339Nano)
	if job.StartedAt == "" {
		job.StartedAt = now
	}
	if job.CreatedAt == "" {
		job.CreatedAt = now
	}
	if job.UpdatedAt == "" {
		job.UpdatedAt = now
	}
	if job.Progress < 0 {
		job.Progress = 0
	}
	if job.Progress > 100 {
		job.Progress = 100
	}
	_, err := s.execDB(context.Background(), "scan_job_insert", `
INSERT INTO scan_jobs (
  job_id, kind, mode, agent_id, resource_id, status, progress,
  rule_version, trigger, scope_json, result_json, phase, current, total,
  cancel_requested, idempotency_key, started_at, finished_at, error, created_at, updated_at
) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		job.JobID, job.Kind, job.Mode, job.AgentID, job.ResourceID, job.Status, job.Progress,
		job.RuleVersion, job.Trigger, encodeJobJSON(job.Scope), encodeJobJSON(job.Result), job.Phase,
		job.Current, job.Total, boolToInt(job.CancelRequested), strings.TrimSpace(job.IdempotencyKey),
		job.StartedAt, nullStringOrNil(job.FinishedAt), nullStringOrNil(job.Error), job.CreatedAt, job.UpdatedAt,
	)
	return err
}

// UpdateScanJob persists the latest state of a running/completed job.
func (s *Store) UpdateScanJob(job ScanJob) error {
	if s == nil || s.db == nil {
		return nil
	}
	job.normalizeAliases()
	job.JobID = strings.TrimSpace(job.JobID)
	if job.JobID == "" {
		return fmt.Errorf("audit: scan job id is required")
	}
	if job.UpdatedAt == "" {
		job.UpdatedAt = time.Now().UTC().Format(time.RFC3339Nano)
	}
	_, err := s.execDB(context.Background(), "scan_job_update", `
UPDATE scan_jobs
SET kind = ?, mode = ?, agent_id = ?, resource_id = ?, status = ?, progress = ?,
    rule_version = ?, trigger = ?, scope_json = ?, result_json = ?, phase = ?,
    current = ?, total = ?, cancel_requested = ?, idempotency_key = ?,
    started_at = ?, finished_at = ?, error = ?, updated_at = ?
WHERE job_id = ?`,
		job.Kind, job.Mode, job.AgentID, job.ResourceID, job.Status, job.Progress,
		job.RuleVersion, job.Trigger, encodeJobJSON(job.Scope), encodeJobJSON(job.Result), job.Phase,
		job.Current, job.Total, boolToInt(job.CancelRequested), strings.TrimSpace(job.IdempotencyKey),
		job.StartedAt, nullStringOrNil(job.FinishedAt), nullStringOrNil(job.Error), job.UpdatedAt, job.JobID,
	)
	return err
}

// FindScanJobByIdempotencyKey returns a previously created job for a
// client-supplied retry key. Empty keys intentionally do not deduplicate.
func (s *Store) FindScanJobByIdempotencyKey(key string) (ScanJob, bool, error) {
	if s == nil || s.db == nil || strings.TrimSpace(key) == "" {
		return ScanJob{}, false, nil
	}
	var id string
	err := s.db.QueryRowContext(context.Background(),
		`SELECT job_id FROM scan_jobs WHERE idempotency_key = ? AND "delete" = 0 LIMIT 1`, strings.TrimSpace(key)).Scan(&id)
	if err == sql.ErrNoRows {
		return ScanJob{}, false, nil
	}
	if err != nil {
		return ScanJob{}, false, err
	}
	return s.GetScanJob(id)
}

// GetScanJob loads one durable scan status. Not-found is represented by
// (zero,false,nil), matching the read helpers used by page APIs.
func (s *Store) GetScanJob(jobID string) (ScanJob, bool, error) {
	if s == nil || s.db == nil || strings.TrimSpace(jobID) == "" {
		return ScanJob{}, false, nil
	}
	var job ScanJob
	var finished, scanErr, scopeJSON, resultJSON sql.NullString
	var cancelRequested int
	err := s.db.QueryRowContext(context.Background(), `
SELECT job_id, kind, mode, agent_id, resource_id, status, progress,
       rule_version, trigger, scope_json, result_json, phase, current, total,
       cancel_requested, idempotency_key, started_at, finished_at, error, created_at, updated_at
FROM scan_jobs WHERE job_id = ? AND "delete" = 0`, strings.TrimSpace(jobID)).Scan(
		&job.JobID, &job.Kind, &job.Mode, &job.AgentID, &job.ResourceID, &job.Status, &job.Progress,
		&job.RuleVersion, &job.Trigger, &scopeJSON, &resultJSON, &job.Phase, &job.Current, &job.Total,
		&cancelRequested, &job.IdempotencyKey, &job.StartedAt, &finished, &scanErr, &job.CreatedAt, &job.UpdatedAt,
	)
	if err == sql.ErrNoRows {
		return ScanJob{}, false, nil
	}
	if err != nil {
		return ScanJob{}, false, err
	}
	if finished.Valid {
		job.FinishedAt = finished.String
	}
	if scanErr.Valid {
		job.Error = scanErr.String
	}
	job.Scope = decodeJobJSON(scopeJSON)
	job.Result = decodeJobJSON(resultJSON)
	job.CancelRequested = cancelRequested != 0
	job.normalizeAliases()
	return job, true, nil
}

// ListScanJobs returns newest jobs first. Empty kind/status values do not
// filter that dimension; pagination is deliberately bounded for the local
// desktop history view.
func (s *Store) ListScanJobs(kind, status string, limit, offset int) ([]ScanJob, error) {
	return s.ListScanJobsFiltered(ScanJobFilter{Kind: kind, Status: status, Limit: limit, Offset: offset})
}

// ScanJobFilter adds optional time bounds to the durable job history query
// while keeping ListScanJobs backwards compatible with older callers.
type ScanJobFilter struct {
	Kind   string
	Status string
	Since  time.Time
	Until  time.Time
	Limit  int
	Offset int
}

func (s *Store) ListScanJobsFiltered(f ScanJobFilter) ([]ScanJob, error) {
	if s == nil || s.db == nil {
		return nil, nil
	}
	if f.Limit <= 0 || f.Limit > 500 {
		f.Limit = 100
	}
	if f.Offset < 0 {
		f.Offset = 0
	}
	where := []string{`"delete" = 0`}
	args := []any{}
	if value := strings.TrimSpace(f.Kind); value != "" {
		where = append(where, "kind = ?")
		args = append(args, value)
	}
	if value := strings.TrimSpace(f.Status); value != "" {
		where = append(where, "status = ?")
		args = append(args, value)
	}
	if !f.Since.IsZero() {
		where = append(where, "created_at >= ?")
		args = append(args, f.Since.UTC().Format(time.RFC3339Nano))
	}
	if !f.Until.IsZero() {
		where = append(where, "created_at <= ?")
		args = append(args, f.Until.UTC().Format(time.RFC3339Nano))
	}
	args = append(args, f.Limit, f.Offset)
	rows, err := s.queryDB(context.Background(), "scan_jobs_list", `
SELECT job_id, kind, mode, agent_id, resource_id, status, progress,
       rule_version, trigger, scope_json, result_json, phase, current, total,
       cancel_requested, idempotency_key, started_at, finished_at, error, created_at, updated_at
FROM scan_jobs WHERE `+strings.Join(where, " AND ")+`
ORDER BY created_at DESC LIMIT ? OFFSET ?`, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []ScanJob
	for rows.Next() {
		var job ScanJob
		var finished, scanErr, scopeJSON, resultJSON sql.NullString
		var cancelRequested int
		if err := rows.Scan(
			&job.JobID, &job.Kind, &job.Mode, &job.AgentID, &job.ResourceID,
			&job.Status, &job.Progress, &job.RuleVersion, &job.Trigger, &scopeJSON, &resultJSON,
			&job.Phase, &job.Current, &job.Total, &cancelRequested, &job.IdempotencyKey,
			&job.StartedAt, &finished, &scanErr,
			&job.CreatedAt, &job.UpdatedAt,
		); err != nil {
			return nil, err
		}
		if finished.Valid {
			job.FinishedAt = finished.String
		}
		if scanErr.Valid {
			job.Error = scanErr.String
		}
		job.Scope = decodeJobJSON(scopeJSON)
		job.Result = decodeJobJSON(resultJSON)
		job.CancelRequested = cancelRequested != 0
		job.normalizeAliases()
		out = append(out, job)
	}
	return out, rows.Err()
}

// CountScanJobs returns the total number of matching non-deleted jobs so a
// client can render pagination without confusing page count with total count.
func (s *Store) CountScanJobs(kind, status string) (int, error) {
	return s.CountScanJobsFiltered(ScanJobFilter{Kind: kind, Status: status})
}

func (s *Store) CountScanJobsFiltered(f ScanJobFilter) (int, error) {
	if s == nil || s.db == nil {
		return 0, nil
	}
	where := []string{`"delete" = 0`}
	args := []any{}
	if value := strings.TrimSpace(f.Kind); value != "" {
		where = append(where, "kind = ?")
		args = append(args, value)
	}
	if value := strings.TrimSpace(f.Status); value != "" {
		where = append(where, "status = ?")
		args = append(args, value)
	}
	if !f.Since.IsZero() {
		where = append(where, "created_at >= ?")
		args = append(args, f.Since.UTC().Format(time.RFC3339Nano))
	}
	if !f.Until.IsZero() {
		where = append(where, "created_at <= ?")
		args = append(args, f.Until.UTC().Format(time.RFC3339Nano))
	}
	var total int
	if err := s.db.QueryRowContext(context.Background(),
		`SELECT COUNT(*) FROM scan_jobs WHERE `+strings.Join(where, " AND "), args...).Scan(&total); err != nil {
		return 0, err
	}
	return total, nil
}

func boolToInt(value bool) int {
	if value {
		return 1
	}
	return 0
}

// MarkRunningScanJobsFailed prevents a job from remaining forever in
// "running" after the gateway process is restarted before its goroutine can
// publish the terminal state.
func (s *Store) MarkRunningScanJobsFailed() error {
	if s == nil || s.db == nil {
		return nil
	}
	now := time.Now().UTC().Format(time.RFC3339Nano)
	_, err := s.execDB(context.Background(), "scan_jobs_recover", `
UPDATE scan_jobs
SET status = 'failed', progress = 0, finished_at = ?,
    error = 'gateway restarted before scan completion', updated_at = ?
WHERE status IN ('queued', 'running') AND "delete" = 0`, now, now)
	return err
}

func nullStringOrNil(value string) any {
	if strings.TrimSpace(value) == "" {
		return nil
	}
	return value
}
